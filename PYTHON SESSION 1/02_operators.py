# LOGICAL OPERATORS

v = (5>10) and (10>5)
print(v) # logical and operator

t = (5>10) or (10>5)
print(t) # logical or operator

j = not(5>10)
print(j) # logical not operator

o = (5>10) and not(10>5)
print(o) # logical and operator with not operator

p = (5>10) or not(10>5)
print(p) # logical or operator with not operator

s = (5>10) and (10>5) or not(10>5)
print(s) # logical and operator with logical or operator and not operator